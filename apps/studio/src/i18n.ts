/** Who made a change, for people: "Claude (MCP)" rather than "mcp:Claude". */
export function viaName(via: string): string {
  if (via.startsWith("mcp:")) {
    const who = via.slice(4);
    return who === "stdio" || who === "local" ? (uiLang.value === "ar" ? "ذكاء اصطناعي (MCP)" : "an AI (MCP)") : `${who} (MCP)`;
  }
  if (via === "studio") return uiLang.value === "ar" ? "الاستوديو" : "the studio";
  if (via === "worker") return uiLang.value === "ar" ? "الخادم" : "the server";
  return via;
}

export function ago(ms: number): string {
  const s = Math.max(0, (Date.now() - ms) / 1000);
  const fmt = new Intl.RelativeTimeFormat(uiLang.value, { numeric: "auto" });
  if (s < 60) return fmt.format(-Math.round(s), "second");
  if (s < 3600) return fmt.format(-Math.round(s / 60), "minute");
  if (s < 86400) return fmt.format(-Math.round(s / 3600), "hour");
  return fmt.format(-Math.round(s / 86400), "day");
}

