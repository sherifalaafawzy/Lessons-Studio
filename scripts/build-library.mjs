// Builds the shared library from a Darsi course pack: the cast (5 people × 4 moods), the pack's 115 icons as stroke
// paths, and the Darsi mark. Lessons use them through `@lib/v1/...` paths; Hosting serves them from /lib/v1/.
//   node scripts/build-library.mjs <unzipped Darsi_AI-basics_pilot folder>
// Writes apps/studio/public/lib/v1/{cast/*.svg, icons.json, brand/darsi-mark.svg} and packages/spec/src/library-icons.ts.
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const pack = process.argv[2];
if (!pack) { console.error("Usage: node scripts/build-library.mjs <Darsi_AI-basics_pilot folder>"); process.exit(1); }
const assets = join(pack, "06_Source-and-templates", "assets");
const out = join(root, "apps", "studio", "public", "lib", "v1");
mkdirSync(join(out, "cast"), { recursive: true });
mkdirSync(join(out, "brand"), { recursive: true });

// The cast: only the SVGs (each about 1.7 KB).
let cast = 0;
for (const f of readdirSync(join(assets, "cast"))) {
  if (!/^[a-z]+_(curious|happy|smile|talking)\.svg$/.test(f)) continue;
  copyFileSync(join(assets, "cast", f), join(out, "cast", f));
  cast++;
}
copyFileSync(join(assets, "mark.svg"), join(out, "brand", "darsi-mark.svg"));

// Icons: every shape becomes one path, so the player draws them like its own (stroke, the brand tone).
const num = (s) => Number(s ?? 0);
const attrs = (tag) => Object.fromEntries([...tag.matchAll(/([A-Za-z][A-Za-z0-9:-]*)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
function toPath(name, a) {
  switch (name) {
    case "path": return a.d;
    case "line": return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline": return `M${a.points.trim().replace(/\s+/g, " ")}`;
    case "polygon": return `M${a.points.trim().replace(/\s+/g, " ")}Z`;
    case "circle": {
      const cx = num(a.cx), cy = num(a.cy), r = num(a.r);
      return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`;
    }
    case "ellipse": {
      const cx = num(a.cx), cy = num(a.cy), rx = num(a.rx), ry = num(a.ry);
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`;
    }
    case "rect": {
      const x = num(a.x), y = num(a.y), w = num(a.width), h = num(a.height);
      const r = Math.min(num(a.rx ?? a.ry), w / 2, h / 2);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
    }
  }
  throw new Error(`Unknown SVG element ${name}`);
}
const src = JSON.parse(readFileSync(join(assets, "icons.json"), "utf8"));
const icons = {};
for (const [name, svg] of Object.entries(src)) {
  icons[name] = [...svg.matchAll(/<(path|line|polyline|polygon|circle|ellipse|rect)\b([^>]*)>/g)].map((m) => toPath(m[1], attrs(m[2])));
}
// A shape whose attributes weren't all read would draw nothing: refuse it rather than ship a broken icon.
for (const [name, paths] of Object.entries(icons)) {
  if (!paths.length || paths.some((d) => !d || /undefined|NaN/.test(d))) throw new Error(`Icon ${name} didn't convert: ${JSON.stringify(paths)}`);
}
writeFileSync(join(out, "icons.json"), JSON.stringify(icons));

const names = Object.keys(icons).sort();
writeFileSync(join(root, "packages", "spec", "src", "library-icons.ts"), `// Generated by scripts/build-library.mjs from the Darsi pack's icon set: the icons in the shared library (@lib/v1/icons.json).
export const LIBRARY_ICONS = ${JSON.stringify(names)} as const;
export type LibraryIcon = (typeof LIBRARY_ICONS)[number];
`);
console.log(`library: ${cast} cast files, ${names.length} icons, the Darsi mark -> apps/studio/public/lib/v1`);
