// Builds the Lesson Studio player for Darsi (createPlayer, packsUsed, prefetchPacks) and copies the shared library
// (cast, icons, the Darsi mark) beside it, so Darsi plays light lessons from its own address. Each technology pack
// (science, code, data, iot, network, opt) stays a file of its own, lessonstudio-pack-<id>.js, that the player imports
// only for lessons that use it, so Darsi's bundler keeps each one a lazy chunk; lessonstudio-chunk-*.js is shared code.
//   node scripts/darsi/vendor-player.mjs [Darsi repository, default ../darsi]
import { build } from "esbuild";
import { cpSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { basename, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../../", import.meta.url));
const darsi = resolve(process.argv[2] ?? join(ROOT, "..", "darsi"));
const dir = join(darsi, "apps", "web", "src", "vendor");
const player = join(ROOT, "packages", "player", "src");
const packs = Object.fromEntries(["code", "data", "iot", "network", "opt"].map((id) => [`lessonstudio-pack-${id}`, join(player, "packs", id, "index.ts")]));
const out = await build({
  // The packs are entry points too, so the player's import("./packs/…") points at these files by name.
  entryPoints: { "lessonstudio-player": join(ROOT, "scripts", "darsi", "vendor-entry.ts"), "lessonstudio-pack-science": join(player, "science", "index.ts"), ...packs },
  bundle: true, minify: true, format: "esm", target: "es2020", splitting: true, outdir: dir,
  entryNames: "[name]", chunkNames: "lessonstudio-chunk-[hash]", write: false, legalComments: "none", logLevel: "warning",
});
mkdirSync(dir, { recursive: true });
// Old builds' files go first (chunk names change); the hand-written types stay.
for (const f of readdirSync(dir)) if (/^lessonstudio-.*\.js$/.test(f)) rmSync(join(dir, f));
const sizes = [];
for (const f of out.outputFiles) {
  const name = basename(f.path);
  writeFileSync(join(dir, name), `// Generated by Lesson Studio's scripts/darsi/vendor-player.mjs from @lessonstudio/player: do not edit.\n${f.text}`);
  sizes.push(`${name} ${Math.round(f.contents.length / 1024)} KB`);
}
cpSync(join(ROOT, "apps", "studio", "public", "lib"), join(darsi, "apps", "web", "public", "lib"), { recursive: true });
console.log(`${sizes.join(", ")} -> ${dir}; library -> apps/web/public/lib`);
