// Builds the Lesson Studio player for Darsi (only createPlayer, as one ES module) and copies the shared library
// (cast, icons, the Darsi mark) beside it, so Darsi plays light lessons from its own address.
//   node scripts/darsi/vendor-player.mjs [Darsi repository, default ../darsi]
import { build } from "esbuild";
import { cpSync, mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../../", import.meta.url));
const darsi = resolve(process.argv[2] ?? join(ROOT, "..", "darsi"));
const out = await build({
  stdin: { contents: 'export { createPlayer } from "@lessonstudio/player";', resolveDir: ROOT, loader: "ts" },
  bundle: true, minify: true, format: "esm", target: "es2020", write: false, legalComments: "none", logLevel: "warning",
});
const dir = join(darsi, "apps", "web", "src", "vendor");
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, "lessonstudio-player.js"),
  `// Generated by Lesson Studio's scripts/darsi/vendor-player.mjs from @lessonstudio/player: do not edit.\n${out.outputFiles[0].text}`);
cpSync(join(ROOT, "apps", "studio", "public", "lib"), join(darsi, "apps", "web", "public", "lib"), { recursive: true });
console.log(`player: ${Math.round(out.outputFiles[0].contents.length / 1024)} KB -> ${dir}; library -> apps/web/public/lib`);
