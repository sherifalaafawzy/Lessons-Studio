// Builds Lesson Studio's checker and timing estimate (validatePackage, estimateTiming) for Darsi's Cloud Functions, which
// turn the tutor agent's explainers into lesson packages and check them before a phone plays them. One ESM file for Node;
// its types are hand-written in Darsi (functions/vendor/lessonstudio-spec.d.ts).
//   node scripts/darsi/vendor-spec.mjs [Darsi repository, default ../darsi]
import { build } from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../../", import.meta.url));
const darsi = resolve(process.argv[2] ?? join(ROOT, "..", "darsi"));
const dir = join(darsi, "functions", "vendor");
const out = await build({
  stdin: { contents: 'export { validatePackage, estimateTiming, TEMPLATES, ICONS } from "./packages/spec/src/index.ts";', resolveDir: ROOT, loader: "ts" },
  bundle: true, format: "esm", platform: "node", target: "node22", write: false, legalComments: "none", logLevel: "warning",
});
mkdirSync(dir, { recursive: true });
const file = join(dir, "lessonstudio-spec.js");
writeFileSync(file, `// Generated by Lesson Studio's scripts/darsi/vendor-spec.mjs from @lessonstudio/spec: do not edit.\n${out.outputFiles[0].text}`);
console.log(`lessonstudio-spec.js ${Math.round(out.outputFiles[0].contents.length / 1024)} KB -> ${dir}`);
